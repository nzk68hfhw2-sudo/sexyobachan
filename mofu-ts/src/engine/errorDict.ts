// =============================================================
// TypeScript のエラーには、それぞれ番号（TS2322 など）がついています。
// 番号ごとに「何が起きているか」を箱のたとえで説明します。
//
// 英語の原文の中から型の名前などを取り出して、説明に入れています。
// 例: Type 'string' is not assignable to type 'number'.
//   → 「number（数字）の箱に、string（文字）を入れようとしてるよ」
// =============================================================

/**
 * 型の名前を、日本語のふりがなつきにする。
 * 例: "string" → "string（文字）"
 */
export function describeType(t: string): string {
  const s = t.trim();
  if (s === "string") return "string（文字）";
  if (s === "number") return "number（数字）";
  if (s === "boolean") return "boolean（はい・いいえ）";
  if (s === "true" || s === "false") return `${s}（はい・いいえ）`;
  if (s === "undefined") return "undefined（からっぽ）";
  if (s === "null") return "null（わざとからっぽ）";
  if (/^".*"$/.test(s)) return `文字の ${s}`;
  if (/^-?\d/.test(s)) return `数字の ${s}`;
  if (s === "string[]") return "string[]（文字が並んだ棚）";
  if (s === "number[]") return "number[]（数字が並んだ棚）";
  if (s === "boolean[]") return "boolean[]（はい・いいえが並んだ棚）";
  if (s.startsWith("{")) return "その形のオブジェクト";
  return s;
}

/** 英語の原文から、'...' で囲まれた部分を順番に取り出す */
function quoted(message: string): string[] {
  // 1行目だけを見る（2行目以降はくわしい理由が続くことが多い）
  const first = message.split("\n")[0] ?? "";
  const found: string[] = [];
  const re = /'((?:[^'\\]|\\.)*)'/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(first)) !== null) found.push(m[1] ?? "");
  return found;
}

