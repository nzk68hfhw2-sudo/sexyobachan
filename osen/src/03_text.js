// ---- 謎日本語・中華フォント混ぜ -----------------------------------------------
// CN_GLYPH : 日本語と中国語で字の形が違う漢字 → 中国語フォント(簡体字の字形)で表示
// CN_SIMP  : 文中にまぎれこむ簡体字（そもそも日本語にない字）
var CN_GLYPH = '直骨角令冷領画海写次器底誤真具値説返道遍過強歩着半化消亮';
var CN_SIMP = '这请们说东车门气鸡热买卖样过对时间开关进来吗吧电视场谢欢迎为专业产品质务员乐书爱认识发现总点击处听话语见长让们';
var CN_CHARS_ALL = (function () { var s = CN_GLYPH + CN_SIMP, o = ''; for (var i = 0; i < s.length; i++) if (o.indexOf(s[i]) < 0) o += s[i]; return o; })();
function isCN(ch) { return CN_CHARS_ALL.indexOf(ch) >= 0; }
function cnSegments(str) {
  var out = [], cur = '', curCn = null;
  for (var i = 0; i < str.length; i++) {
    var ch = str[i], c = isCN(ch);
    if (curCn === null) curCn = c;
    if (c !== curCn) { out.push({ t: cur, cn: curCn }); cur = ''; curCn = c; }
    cur += ch;
  }
  if (cur) out.push({ t: cur, cn: curCn });
  return out;
}
function escHTML(s) { return String(s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }
function cnHTML(str) {
  return cnSegments(String(str)).map(function (s) {
    var t = escHTML(s.t).replace(/\n/g, '<br>');
    return s.cn ? '<span class="cn" lang="zh-CN">' + t + '</span>' : t;
  }).join('');
}

